class Command(BaseCommand):
    help = 'Seed the Tip table with the curated Arabic and English tips.'

    def handle(self, *args, **options):
        created_ar = self._seed(ARABIC_TIPS, 'ar')
        created_en = self._seed(ENGLISH_TIPS, 'en')

        self.stdout.write(self.style.SUCCESS(
            f'Added {created_ar} Arabic tips and {created_en} English tips.'
        ))

    def _seed(self, texts, locale):
        created = 0
        for text in texts:
            _, was_created = Tip.objects.get_or_create(
                text=text,
                locale=locale,
                defaults={'is_active': True},
            )
            if was_created:
                created += 1
        return created